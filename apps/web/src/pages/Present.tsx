const OFFLINE_ERROR = new ApiError('API unreachable', 0);

const FALLBACK_DEMO: SimulateRequest = { scenario: 'normal', horizon: { hours: 168, start_day: 14, resolution_h: 1 } };

/** Demo request: the verified input of `ref-demo-week` when it exists, else normal 168 h from day 14. */
function demoRequestFrom(ref: RunPayload | null): { body: SimulateRequest; source: 'reference-input' | 'fallback' } {
  const inp = ref?.input as Partial<SimulateRequest> | undefined;
  if (inp && typeof inp.scenario === 'string' && inp.horizon) {
    return {
      body: { scenario: inp.scenario, scenario_overrides: inp.scenario_overrides ?? {}, system: inp.system ?? {}, horizon: inp.horizon },
      source: 'reference-input',
    };
  }
  return { body: FALLBACK_DEMO, source: 'fallback' };
}

const isTyping = (t: EventTarget | null) => {
  const el = t as HTMLElement | null;
  return !!el && (el.tagName === 'INPUT' || el.tagName === 'SELECT' || el.tagName === 'TEXTAREA' || el.isContentEditable);
};

function StepFrame({ eyebrow, title, children }: { eyebrow: string; title: ReactNode; children: ReactNode }) {
  return (
    <div className="space-y-5">
      <div>
        <div className="eyebrow mb-2 text-hydro">{eyebrow}</div>
        <h2 className="font-serif text-[2rem] font-medium leading-tight tracking-tight text-ink sm:text-[2.6rem]">{title}</h2>
      </div>
      {children}
    </div>
  );
}

function ReferenceRun({ id, note }: { id: string; note: string }) {
  const ref = useExperiment(id);
  if (ref.loading) return <LoadingBlock height={300} label={`Loading reference experiment ${id}…`} />;
  if (!ref.data || !isRunPayload(ref.data))
    return (
      <EmptyState title={`Reference experiment ${id} is not available yet`}>
        It is generated by the experiment pipeline and appears here automatically once it exists.
      </EmptyState>
    );
  return (
    <div className="space-y-3">
      <Callout tone="uncertainty" title="Reference experiment — not computed now">
        {note}
      </Callout>
      <CompactRun run={ref.data} />
    </div>
  );
}

