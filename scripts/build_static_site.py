"""Build the public static deployment of the HydroFlex AI web app.

    cd apps/web && VITE_API_BASE= npm run build      # same-origin API paths
    python scripts/build_static_site.py              # writes dist/api-static/*, _redirects, _headers, paper PDF

All JSON served by the static site is produced by the real FastAPI application (TestClient) from the
reference experiment files — nothing is hand-written. Only *reference* experiments are included (no session
runs). POST endpoints (live optimisation) are answered with an explicit 503 JSON explaining that the static
deployment has no solver.
"""

from __future__ import annotations

import datetime as dt
import json
import os
import shutil
from pathlib import Path

os.environ.setdefault("HYDROFLEX_RATE_LIMIT", "100000")

from fastapi.testclient import TestClient  # noqa: E402

from hydroflex import REPO_ROOT  # noqa: E402
from hydroflex_api.main import app  # noqa: E402

DIST = REPO_ROOT / "apps" / "web" / "dist"
OUT = DIST / "api-static"


def dump(path: Path, obj: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, separators=(",", ":"), allow_nan=False), encoding="utf-8")


def main() -> None:
    if not (DIST / "index.html").exists():
        raise SystemExit("apps/web/dist missing: run `VITE_API_BASE= npm run build` in apps/web first")
    if OUT.exists():
        shutil.rmtree(OUT)
    c = TestClient(app)
    now = dt.datetime.now(dt.UTC).isoformat(timespec="seconds").replace("+00:00", "Z")

    health = c.get("/api/health").json()
    health.update({"deployment": "static-snapshot", "snapshot_created_utc": now, "solver_busy": False})
    dump(OUT / "health.json", health)
    for name, url in (("metadata", "/api/model/metadata"), ("sources", "/api/data/sources"), ("scenarios", "/api/scenarios"),
                      ("profiles", "/api/data/profiles?start_day=0&days=365&resolution_h=24")):
        r = c.get(url)
        r.raise_for_status()
        dump(OUT / f"{name}.json", r.json())

    exps = [e for e in c.get("/api/experiments").json()["experiments"] if e["reference"]]
    dump(OUT / "experiments.json", {"experiments": exps})
    for e in exps:
        rid = e["run_id"]
        d = c.get(f"/api/experiments/{rid}").json()
        dump(OUT / "experiments" / f"{rid}.json", d)
        for fmt, ext in (("csv", "csv"), ("metrics_csv", "metrics.csv")):
            if d.get("timeseries", {}).get("timestamps") or fmt == "metrics_csv":
                r = c.get(f"/api/experiments/{rid}/download?format={fmt}")
                if r.status_code == 200:
                    (OUT / "downloads").mkdir(parents=True, exist_ok=True)
                    (OUT / "downloads" / f"{rid}.{ext}").write_bytes(r.content)
    dump(OUT / "unavailable.json", {
        "detail": "Live optimisation is not available on this static deployment. It serves the verified reference "
                  "experiments only. Run the FastAPI backend locally (see README) for live HiGHS solves."})

    paper = REPO_ROOT / "research" / "paper" / "HydroFlex_AI_Research_Paper.pdf"
    if paper.exists():
        shutil.copy2(paper, DIST / "HydroFlex_AI_Research_Paper.pdf")
    poster = REPO_ROOT / "research" / "poster" / "HydroFlex_AI_Poster.pdf"
    if poster.exists():
        shutil.copy2(poster, DIST / "HydroFlex_AI_Poster.pdf")

    redirects = [
        "# Generated by scripts/build_static_site.py",
        "/api/health                 /api-static/health.json            200",
        "/api/model/metadata         /api-static/metadata.json          200",
        "/api/data/sources           /api-static/sources.json           200",
        "/api/data/profiles          /api-static/profiles.json          200",
        "/api/scenarios              /api-static/scenarios.json         200",
        "/api/experiments            /api-static/experiments.json       200",
        "/api/experiments/:id/download  format=csv          /api-static/downloads/:id.csv          200",
        "/api/experiments/:id/download  format=metrics_csv  /api-static/downloads/:id.metrics.csv  200",
        "/api/experiments/:id/download  /api-static/experiments/:id.json  200",
        "/api/experiments/:id        /api-static/experiments/:id.json   200",
        "/api/paper                  /HydroFlex_AI_Research_Paper.pdf   200",
        "/api/*                      /api-static/unavailable.json       503",
        "/*                          /index.html                        200",
    ]
    (DIST / "_redirects").write_text("\n".join(redirects) + "\n", encoding="utf-8")
    (DIST / "_headers").write_text(
        "/*\n  X-Content-Type-Options: nosniff\n  Referrer-Policy: strict-origin-when-cross-origin\n"
        "  X-Frame-Options: SAMEORIGIN\n/api-static/*\n  Cache-Control: public, max-age=3600\n"
        "  Access-Control-Allow-Origin: *\n/assets/*\n  Cache-Control: public, max-age=31536000, immutable\n",
        encoding="utf-8")
    size = sum(p.stat().st_size for p in DIST.rglob("*") if p.is_file())
    print(f"static site ready: {len(exps)} reference experiments, {size / 1e6:.1f} MB in {DIST}")


if __name__ == "__main__":
    main()
