"""Load processed model inputs; fall back to fully synthetic profiles when processed data are absent."""

from __future__ import annotations

import json
from functools import lru_cache

import numpy as np
import pandas as pd

from hydroflex import DATA_DIR, SYNTHETIC_LABEL

PROCESSED = DATA_DIR / "processed"
SYNTH = DATA_DIR / "synthetic"
COLUMNS = ["pv_cf", "wind_cf", "demand_mw", "import_price_eur_mwh", "drin_inflow_hm3_per_h", "ror_avail_mw"]


def reference_year() -> int | None:
    f = PROCESSED / "profile_summary.json"
    if f.exists():
        return int(json.loads(f.read_text(encoding="utf-8"))["reference_year"])
    return None


@lru_cache(maxsize=8)
def load_profiles(year: int | None = None) -> tuple[pd.DataFrame, str]:
    """Return (hourly profile frame indexed in UTC, data_mode).

    data_mode is "weather-derived+reconstructed+synthetic" for processed data built from NASA POWER,
    or "synthetic" for the fully synthetic fallback.
    """
    year = year or reference_year()
    if year is not None:
        f = PROCESSED / f"hourly_profiles_{year}.csv"
        if f.exists():
            df = pd.read_csv(f, index_col=0, parse_dates=True)
            df.index = pd.DatetimeIndex(df.index, tz="UTC") if df.index.tz is None else df.index
            df.attrs["year"] = year
            return df, "weather-derived+reconstructed+synthetic"
    return synthetic_profiles(), "synthetic"


def synthetic_profiles(seed: int = 7, hours: int = 8760) -> pd.DataFrame:
    """Fully synthetic fallback profiles (documented formulas, fixed seed).

    SYNTHETIC RESEARCH DEMONSTRATION DATA — NOT OBSERVED GRID OPERATIONS.
    """
    rng = np.random.default_rng(seed)
    idx = pd.date_range("2022-01-01", periods=hours, freq="h", tz="UTC")
    doy = idx.dayofyear.to_numpy()
    hour_local = ((idx.hour.to_numpy() + 1) % 24).astype(float)
    season = np.cos(2 * np.pi * (doy - 172) / 365.0)  # +1 midsummer, -1 midwinter
    elev = np.clip(np.sin(np.pi * (hour_local - 6 - season) / (12 + 2 * season)), 0, None)
    cloud = np.clip(1 - 0.35 * rng.beta(2, 5, size=hours) - 0.2 * (1 - season) / 2, 0.2, 1)
    pv = np.clip(0.85 * elev * (0.75 + 0.25 * season) * cloud, 0, 1)
    wind = np.clip(0.11 + 0.06 * (-season) + 0.08 * rng.standard_normal(hours).cumsum() / np.sqrt(hours) * 5, 0, 0.9)
    temp = 15 - 9 * (-season) + 5 * np.sin(np.pi * (hour_local - 9) / 12)
    demand = 900 * (1 + 0.03 * np.clip(16 - temp, 0, None) + 0.035 * np.clip(temp - 24, 0, None))
    demand *= 1 + 0.15 * np.sin(np.pi * (hour_local - 6) / 14).clip(0, None)
    demand *= 8.0e6 * hours / 8760 / demand.sum()
    inflow_season = 1 + 0.65 * np.cos(2 * np.pi * (doy - 60) / 365.0)
    inflow = 0.84 * inflow_season * (1 + 0.15 * rng.standard_normal(hours).cumsum() / np.sqrt(hours))
    ror = np.clip(330 * inflow_season, 0, 930)
    price = 105 * (1 + 0.2 * np.sin(np.pi * (hour_local - 12) / 12) ** 2) * (1 + 0.1 * (-season))
    price *= 105 / price.mean()
    df = pd.DataFrame({"pv_cf": pv, "wind_cf": wind, "demand_mw": demand, "import_price_eur_mwh": price,
                       "drin_inflow_hm3_per_h": np.clip(inflow, 0.05, None), "ror_avail_mw": ror,
                       "t2m_tirana_c": temp}, index=idx)
    df.attrs["label"] = SYNTHETIC_LABEL
    df.attrs["year"] = None
    return df


def write_synthetic_fallback() -> None:
    SYNTH.mkdir(parents=True, exist_ok=True)
    df = synthetic_profiles()
    df.to_csv(SYNTH / "synthetic_hourly_profiles.csv", index_label="timestamp_utc")
    (SYNTH / "README.md").write_text(
        f"# {SYNTHETIC_LABEL}\n\nGenerated by `hydroflex.data.loader.synthetic_profiles(seed=7)`. Used only when the "
        "processed NASA-POWER-derived profiles are unavailable. Formulas are in the source code.\n",
        encoding="utf-8",
    )


def aggregate(df: pd.DataFrame, resolution_h: int) -> pd.DataFrame:
    """Average consecutive blocks of ``resolution_h`` hours (energy-preserving for MW quantities)."""
    if resolution_h == 1:
        return df
    n = (len(df) // resolution_h) * resolution_h
    df = df.iloc[:n]
    grp = np.arange(n) // resolution_h
    out = df.groupby(grp).mean(numeric_only=True)
    out.index = df.index[::resolution_h]
    out.attrs = dict(df.attrs)
    return out
